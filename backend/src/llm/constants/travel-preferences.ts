export const getPreferenceDescription = (values: string | string[]) => {
  if (!values || values.length === 0) return '无特别偏好';
  
  // 处理单选和多选的情况
  const valueArray = Array.isArray(values) ? values : [values];
  
  const selectedPrefs = travelPreferences.filter(p => valueArray.includes(p.value));
  
  if (selectedPrefs.length === 0) return '无特别偏好';
  
  const labels = selectedPrefs.map(p => p.label).join(' + ');
  const prompts = selectedPrefs.map(p => `- 【${p.label}】: ${p.prompt}`).join('\n');
  
  return `本次旅行融合了 ${labels} 的特点。请严格遵循以下细分原则：\n${prompts}`;
};